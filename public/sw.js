/* Architech service worker — offline shell only.

   Scope, deliberately minimal (docs/superpowers/specs/2026-09-11-pwa-installability-design.md):

     * precache the offline fallback + manifest + home-screen icons
     * navigations are network-first; when the network fails, serve /offline.html
     * content-hashed build assets (/_next/static/, /vendor/) are cache-first —
       their URLs change with every build, so a cache hit is never stale
     * everything else, including every /api/ route, is left to the network:
       lead data, saved homes and search results must never be served stale

   There is no build step and no dependency: public/ is copied verbatim by
   ops/scripts/materialize-static-publish.mjs and served by Next.js in dev and
   production. That is why this file is hand-written rather than generated by a
   webpack-only PWA plugin — this repo builds with Turbopack (Next 16).

   IMPORTANT: this file MUST be served with `Cache-Control: no-store` (see
   next.config.ts headers() and ops/scripts/publish-server.mjs). A cached
   service worker is a service worker that never updates. Bump VERSION whenever
   the precached shell changes so clients drop the old cache on activate. */

const VERSION = "architech-v1";
const SHELL_CACHE = `${VERSION}-shell`;
const ASSET_CACHE = `${VERSION}-assets`;
const OFFLINE_URL = "/offline.html";
const PRECACHE_URLS = [
  OFFLINE_URL,
  "/manifest.webmanifest",
  "/icon-192.png",
  "/icon-512.png",
];

self.addEventListener("install", event => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(SHELL_CACHE);
      /* addAll() rejects on the first failing URL and would leave the worker
         uninstalled, so each entry is cached on its own terms. URLs are
         resolved to absolute: a bare path is valid in a browser (resolved
         against the worker's own location) but ambiguous elsewhere, and this
         file is executed by src/lib/pwa/service-worker.test.ts under Node's
         stricter Request. */
      await Promise.all(
        PRECACHE_URLS.map(url =>
          cache
            .add(new Request(new URL(url, self.location.href), { cache: "reload" }))
            .catch(() => undefined)
        )
      );
      await self.skipWaiting();
    })()
  );
});

self.addEventListener("activate", event => {
  event.waitUntil(
    (async () => {
      const keys = await caches.keys();
      await Promise.all(
        keys
          .filter(key => !key.startsWith(VERSION))
          .map(key => caches.delete(key))
      );
      await self.clients.claim();
    })()
  );
});

/* Only URLs whose content is bound to their URL are safe to cache-first. */
function isImmutableAsset(url) {
  return (
    url.pathname.startsWith("/_next/static/") ||
    url.pathname.startsWith("/vendor/")
  );
}

self.addEventListener("fetch", event => {
  const request = event.request;
  if (request.method !== "GET") return;

  const url = new URL(request.url);
  /* Cross-origin requests (OpenStreetMap tiles, Sentry ingest, R2 image
     transforms) are opaque to us and must not be cached. */
  if (url.origin !== self.location.origin) return;
  /* Product data is never cached — a stale lead list is worse than a spinner. */
  if (url.pathname.startsWith("/api/")) return;

  if (request.mode === "navigate") {
    event.respondWith(
      (async () => {
        try {
          return await fetch(request);
        } catch {
          const offline = await caches.match(OFFLINE_URL);
          /* Response.error() would show the browser's own offline interstitial;
             the branded page is only worth serving when it really is cached. */
          return offline ?? Response.error();
        }
      })()
    );
    return;
  }

  if (isImmutableAsset(url)) {
    event.respondWith(
      (async () => {
        const cached = await caches.match(request);
        if (cached) return cached;
        const response = await fetch(request);
        if (response.ok) {
          const cache = await caches.open(ASSET_CACHE);
          void cache.put(request, response.clone()).catch(() => undefined);
        }
        return response;
      })()
    );
  }
});
